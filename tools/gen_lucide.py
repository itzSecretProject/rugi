#!/usr/bin/env python3
"""Generates the Rust and C Lucide icon constants from crates/rugi-icons/assets/lucide-codepoints.json.

Usage: python3 tools/gen_lucide.py
Source: lucide-static (ISC). Re-run after updating the font and its codepoints.
"""
import collections
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CODEPOINTS = ROOT / "crates/rugi-icons/assets/lucide-codepoints.json"
RUST_OUT = ROOT / "crates/rugi-icons/src/lucide.rs"
C_OUT = ROOT / "include/rugi/rugi_icons_lucide.h"

# Bit set on a codepoint to mark a RugiIcon value as a font glyph.
C_GLYPH_FLAG = 0x80000000


def ident(name: str) -> str:
    """`arrow-left` -> `ARROW_LEFT`; a leading digit gets an `N` prefix."""
    s = name.upper().replace("-", "_")
    return "N" + s if s[0].isdigit() else s


def load_icons() -> list[tuple[str, str, int]]:
    """`(name, identifier, codepoint)` for every icon, sorted by name."""
    codepoints = json.loads(CODEPOINTS.read_text())
    icons = [(name, ident(name), cp) for name, cp in sorted(codepoints.items())]
    counts = collections.Counter(i for _, i, _ in icons)
    duplicates = sorted(i for i, n in counts.items() if n > 1)
    assert not duplicates, f"identifier collision: {duplicates}"
    return icons


def rust_source(icons) -> str:
    lines = [
        "// GENERATED by tools/gen_lucide.py from lucide-static codepoints. Do not edit.",
        "//! Lucide icon glyphs (ISC License, see crates/rugi-icons/assets/LUCIDE_LICENSE.txt).",
        "//!",
        "//! Each constant is a one-character string in the Private Use Area that",
        "//! renders with the bundled Lucide font, so icons can be embedded in any",
        "//! label: `ui.button(&format!(\"{} Save\", lucide::SAVE))`.",
        "",
    ]
    for name, i, cp in icons:
        lines.append(f"/// `{name}`")
        lines.append(f'pub const {i}: &str = "\\u{{{cp:04x}}}";')
    lines += [
        "",
        "/// All icons as `(name, glyph)` sorted by name, for lookup by name.",
        "pub const ALL: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{name}", {i}),' for name, i, _ in icons]
    lines += [
        "];",
        "",
        "/// Looks up an icon by its Lucide name (e.g. `\"save\"`).",
        "pub fn by_name(name: &str) -> Option<&'static str> {",
        "    ALL.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| ALL[i].1)",
        "}",
    ]
    return "\n".join(lines) + "\n"


def c_header(icons) -> str:
    lines = [
        "/* GENERATED by tools/gen_lucide.py. Do not edit. */",
        "/* Lucide icons (ISC License, see crates/rugi-icons/assets/LUCIDE_LICENSE.txt). */",
        "/*  RUGI_LUCIDE_<NAME>      UTF-8 string literal, usable inside labels:",
        " *                            rugi_text(ui, RUGI_LUCIDE_SAVE \" Save\", ...)",
        " *  RUGI_ICON_LUCIDE_<NAME> RugiIcon value for icon parameters:",
        " *                            rugi_button(ui, \"Save\", 4, RUGI_BUTTON_PRIMARY, RUGI_ICON_LUCIDE_SAVE) */",
        "#ifndef RUGI_ICONS_LUCIDE_H",
        "#define RUGI_ICONS_LUCIDE_H",
        "",
    ]
    for _, i, cp in icons:
        utf8 = "".join(f"\\x{b:02x}" for b in chr(cp).encode("utf-8"))
        lines.append(f'#define RUGI_LUCIDE_{i} "{utf8}"')
        lines.append(f"#define RUGI_ICON_LUCIDE_{i} 0x{C_GLYPH_FLAG | cp:08x}u")
    lines += ["", "#endif /* RUGI_ICONS_LUCIDE_H */"]
    return "\n".join(lines) + "\n"


def main() -> None:
    icons = load_icons()
    RUST_OUT.write_text(rust_source(icons))
    C_OUT.write_text(c_header(icons))
    print(f"generated {len(icons)} icons")


if __name__ == "__main__":
    main()
